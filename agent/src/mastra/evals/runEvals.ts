/**
 * Standalone batch evaluation script.
 *
 * Usage (after building or with ts-node / tsx):
 *   npx tsx src/mastra/evals/runEvals.ts
 *
 * Populate ragDataset and sqlDataset with real examples from your system.
 * Each RAG item must include `output.context` (the retrieved chunks) so the
 * context-based scorers can run.  Provide `groundTruth` for contextRecallScorer.
 */

import { runEvals } from '@mastra/core/evals';
import { mastra } from '../index.js';
import { ragScorerSet, textToSqlScorerSet } from './index.js';

// ─── RAG evaluation dataset ───────────────────────────────────────────────────
// Replace placeholder strings with real queries, retrieved chunks, and answers
// captured from your clinicalQueryWorkflow runs.
const ragDataset = [
  {
    // The query sent to the agent
    input: 'What medications is patient John Doe currently prescribed?',
    // Ground truth used by contextRecallScorer
    groundTruth:
      'John Doe is prescribed metformin 500 mg twice daily and lisinopril 10 mg once daily.',
    // Pre-captured workflow output — fill in from a real run
    output: {
      text: 'John Doe is on metformin 500 mg and lisinopril 10 mg.',
      context: [
        'Progress note 2024-01-10: Patient John Doe started on metformin 500 mg BID for type-2 diabetes.',
        'Prescription record 2024-02-01: Lisinopril 10 mg QD added for hypertension management.',
        'Discharge summary 2023-12-15: Patient is a 58-year-old male with no known drug allergies.',
      ],
    },
  },
  // Add more items here
];

// ─── Text-to-SQL evaluation dataset ──────────────────────────────────────────
// Populate with natural-language queries, expected SQL, and pre-executed rows.
const sqlDataset = [
  {
    input: {
      query: 'How many patients were admitted last month?',
      expectedSql:
        "SELECT COUNT(*) AS count FROM encounters WHERE admission_date >= date_trunc('month', now() - interval '1 month') AND admission_date < date_trunc('month', now())",
      expectedRows: [{ count: '42' }],
    },
    output: {
      // Fill in the SQL actually generated by clinicalQueryWorkflow
      sql: "SELECT COUNT(*) AS count FROM encounters WHERE admission_date >= date_trunc('month', now() - interval '1 month') AND admission_date < date_trunc('month', now())",
      rows: [{ count: '42' }],
    },
  },
  // Add more items here
];

async function main() {
  const agent = mastra.getAgent('qaAgent');

  // ── RAG metrics ──────────────────────────────────────────────────────────
  console.log('\n─── RAG Evaluation ───────────────────────────────');
  const ragResults = await runEvals({
    target: agent,
    data: ragDataset as Parameters<typeof runEvals>[0]['data'],
    scorers: ragScorerSet,
    onItemComplete: ({ item, scorerResults }) => {
      const query = typeof item.input === 'string' ? item.input : JSON.stringify(item.input);
      console.log(`\nQuery: ${query.slice(0, 80)}`);
      for (const [id, result] of Object.entries(scorerResults)) {
        const r = result as { score: number; reason?: string };
        console.log(`  ${id}: ${r.score.toFixed(2)}  — ${r.reason ?? ''}`);
      }
    },
  });
  console.log('\nRAG aggregate scores:', ragResults.scores);

  // ── Text-to-SQL metrics ───────────────────────────────────────────────────
  console.log('\n─── Text-to-SQL Evaluation ───────────────────────');
  const sqlResults = await runEvals({
    target: agent,
    data: sqlDataset as Parameters<typeof runEvals>[0]['data'],
    scorers: textToSqlScorerSet,
    onItemComplete: ({ item, scorerResults }) => {
      const query = typeof item.input === 'object' && item.input !== null
        ? (item.input as { query?: string }).query ?? JSON.stringify(item.input)
        : String(item.input);
      console.log(`\nQuery: ${query.slice(0, 80)}`);
      for (const [id, result] of Object.entries(scorerResults)) {
        const r = result as { score: number; reason?: string };
        console.log(`  ${id}: ${r.score.toFixed(2)}  — ${r.reason ?? ''}`);
      }
    },
  });
  console.log('\nSQL aggregate scores:', sqlResults.scores);
}

main().catch((err) => {
  console.error('Eval run failed:', err);
  process.exit(1);
});
